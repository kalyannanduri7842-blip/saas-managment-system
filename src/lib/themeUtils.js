/**
 * Theme persistence and DOM class helpers.
 */

/**
 * Theme helper #1.
 */
export function applyTheme1(theme) {
  if (typeof document === "undefined") return;
  if (theme === "dark") document.documentElement.classList.add("dark");
  else document.documentElement.classList.remove("dark");
}

export function getStoredTheme1(key = "saas_theme") {
  try {
    return localStorage.getItem(key) || "light";
  } catch {
    return "light";
  }
}

export function storeTheme1(theme, key = "saas_theme") {
  try {
    localStorage.setItem(key, theme);
    return true;
  } catch {
    return false;
  }
}

export function toggleThemeValue1(current) {
  return current === "dark" ? "light" : "dark";
}


